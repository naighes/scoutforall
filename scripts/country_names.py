#!/usr/bin/env python3
"""Writes core/src/shapes/country_names.rs: the ISO 3166-1 countries with
their names in the languages of the app, from the CLDR data.

    mkdir cldr && for l in en it pt pl ja; do
      curl -sfL -o cldr/$l.json \
        https://cdn.jsdelivr.net/npm/cldr-localenames-full@46.0.0/main/$l/territories.json
    done
    python3 -I scripts/country_names.py cldr > core/src/shapes/country_names.rs

The languages in the order of LanguageEnum.
"""

import json
import sys
from pathlib import Path

LANGUAGES = ["en", "it", "pt", "pl", "ja"]
CLDR_VERSION = "46.0.0"

# the two-letter regions of CLDR that aren't ISO 3166-1 countries
NOT_ISO = {
    "AC", "CP", "CQ", "DG", "EA", "EU", "EZ", "IC", "QO", "TA", "UN",
    "XA", "XB", "XK", "ZZ",
}

# the short name where the full one is a mouthful ("Hong Kong SAR
# China"); not for US and GB, whose short names are the initials
SHORT = {"HK", "MO", "PS"}


def names(folder, language):
    data = json.loads((Path(folder) / f"{language}.json").read_text("utf-8"))
    return data["main"][language]["localeDisplayNames"]["territories"]


def name(territories, code):
    return territories.get(f"{code}-alt-short", territories[code]) if code in SHORT else territories[code]


def main(folder):
    tables = {language: names(folder, language) for language in LANGUAGES}
    codes = sorted(
        code
        for code in tables["en"]
        if len(code) == 2 and code.isalpha() and code not in NOT_ISO
    )
    print(f"//! Generated by `scripts/country_names.py` from CLDR {CLDR_VERSION}: do not edit.")
    print("//! The ISO 3166-1 countries, by code, with their names in the languages")
    print("//! of `LanguageEnum`, in its order.")
    print()
    print("#[rustfmt::skip]")
    print(f"pub(crate) static COUNTRIES: [(&str, [&str; {len(LANGUAGES)}]); {len(codes)}] = [")
    for code in codes:
        translated = ", ".join(json.dumps(name(tables[l], code), ensure_ascii=False) for l in LANGUAGES)
        print(f'    ("{code}", [{translated}]),')
    print("];")


if __name__ == "__main__":
    main(sys.argv[1])
