/// Returns the labels of a language.
pub const fn labels(language: LanguageEnum) -> &'static Labels {
    match language {
        LanguageEnum::En => &EN,
        LanguageEnum::It => &IT,
    }
}

/// A language that can change while the app runs, shared by its clones:
/// the providers hold one to write their errors, the user interface
/// changes it from the settings. The lock only guards a value written at
/// once: it's still good after a panic elsewhere.
#[derive(Clone, Debug)]
pub struct Language(Arc<RwLock<LanguageEnum>>);

impl Language {
    pub fn new(language: LanguageEnum) -> Self {
        Self(Arc::new(RwLock::new(language)))
    }

    pub fn get(&self) -> LanguageEnum {
        *self.0.read().unwrap_or_else(PoisonError::into_inner)
    }

    pub fn set(&self, language: LanguageEnum) {
        *self.0.write().unwrap_or_else(PoisonError::into_inner) = language;
    }

    /// Returns the labels of the language as it is now.
    pub fn labels(&self) -> &'static Labels {
        labels(self.get())
    }
}

impl Default for Language {
    fn default() -> Self {
        Self::new(LanguageEnum::from_str(DEFAULT_LANGUAGE).unwrap_or(LanguageEnum::En))
    }
}
