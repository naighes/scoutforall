static LANGUAGE: LazyLock<Language> = LazyLock::new(Language::default);

/// The language of the app, for the providers that write texts.
pub fn language() -> Language {
    LANGUAGE.clone()
}

/// Changes the language of the labels.
pub fn set_language(language: LanguageEnum) {
    LANGUAGE.set(language);
}

/// Returns the labels for the current language.
pub fn current_labels() -> &'static Labels {
    match LANGUAGE.get() {
        LanguageEnum::En => &EN,
        LanguageEnum::It => &IT,
        LanguageEnum::Pt => &PT,
        LanguageEnum::Pl => &PL,
        LanguageEnum::Ja => &JA,
    }
}

/// An action with its description in the language of the app, e.g.
/// "S (serve)": the actions of the domain have the labels of the domain,
/// those of the screens their own.
pub trait Describe: Sized {
    fn describe(self) -> (Self, String);
}

impl<T: WithDesc<T>> Describe for T {
    fn describe(self) -> (T, String) {
        self.with_desc(current_labels().domain)
    }
}
