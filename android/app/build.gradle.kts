// The core is the Rust crate `mobile` of the workspace, two folders up: cargo
// builds it for Android (cargo-ndk) and for this machine, where UniFFI reads
// the API to generate the Kotlin bindings (the Android build is stripped).
// Cargo knows what changed: the tasks always run it.

/** A cargo command in the workspace, with `~/.cargo/bin` on the path: the
 * IDE doesn't get the one of the shell. */
abstract class CargoTask : DefaultTask() {
    @get:Inject abstract val exec: ExecOperations
    @get:Internal abstract val workspace: DirectoryProperty
    @get:Internal abstract val ndk: DirectoryProperty
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    init {
        outputs.upToDateWhen { false }
    }

    protected fun cargo(vararg args: String) {
        val bin = File(System.getProperty("user.home"), ".cargo/bin")
        exec.exec {
            workingDir = workspace.get().asFile
            environment("PATH", "${bin.path}${File.pathSeparator}${System.getenv("PATH")}")
            environment("ANDROID_NDK_HOME", ndk.get().asFile.path)
            commandLine(listOf(File(bin, "cargo").takeIf { it.exists() }?.path ?: "cargo") + args)
        }
    }
}

/** The core for Android, in the layout of `jniLibs`. */
abstract class CargoNdk : CargoTask() {
    @TaskAction
    fun build() {
        val out = outputDir.get().asFile
        cargo("ndk", "-t", "arm64-v8a", "--platform", "28", "-o", out.path,
            "build", "-p", "scout4all-mobile", "--release")
    }
}

/** The Kotlin bindings of the core. */
abstract class UniffiBindgen : CargoTask() {
    @TaskAction
    fun generate() {
        val os = System.getProperty("os.name").lowercase()
        val library = when {
            os.contains("mac") -> "libscout4all_mobile.dylib"
            os.contains("windows") -> "scout4all_mobile.dll"
            else -> "libscout4all_mobile.so"
        }
        val out = outputDir.get().asFile
        out.deleteRecursively()
        cargo("build", "-p", "scout4all-mobile", "--features", "bindgen")
        cargo("run", "-p", "scout4all-mobile", "--features", "bindgen", "--bin", "uniffi-bindgen",
            "--", "generate", "--library", "target/debug/$library",
            "--language", "kotlin", "--out-dir", out.path, "--no-format")
    }
}

val workspaceDir = rootProject.layout.projectDirectory.dir("..")

val cargoNdk = tasks.register<CargoNdk>("cargoNdk") {
    workspace.set(workspaceDir)
    ndk.set(androidComponents.sdkComponents.ndkDirectory)
    outputDir.set(layout.buildDirectory.dir("generated/rust/jniLibs"))
}

val uniffiBindgen = tasks.register<UniffiBindgen>("uniffiBindgen") {
    workspace.set(workspaceDir)
    ndk.set(androidComponents.sdkComponents.ndkDirectory)
    outputDir.set(layout.buildDirectory.dir("generated/uniffi/kotlin"))
}

/** The permissions of the merged manifest, the ones of the libraries too,
 * are the ones of `permissions.txt`: a new one is a choice (the terms,
 * DATA-PRIVACY, the data safety of Play), not a side effect. */
abstract class VerifyPermissions : DefaultTask() {
    @get:InputFile abstract val manifest: RegularFileProperty
    @get:InputFile abstract val allowed: RegularFileProperty
    @get:OutputFile abstract val checked: RegularFileProperty

    @TaskAction
    fun verify() {
        val document = DocumentBuilderFactory.newInstance().newDocumentBuilder().parse(manifest.get().asFile)
        val declared = listOf("uses-permission", "uses-permission-sdk-23")
            .flatMap { tag ->
                val nodes = document.getElementsByTagName(tag)
                (0 until nodes.length).map { (nodes.item(it) as org.w3c.dom.Element).getAttribute("android:name") }
            }
            .toSortedSet()
        val listed = allowed.get().asFile.readLines()
            .map { it.substringBefore('#').trim() }
            .filter { it.isNotEmpty() }
            .toSortedSet()
        val added = declared - listed
        val removed = listed - declared
        if (added.isNotEmpty() || removed.isNotEmpty()) {
            throw GradleException(
                "the permissions of the app changed: new $added, gone $removed. " +
                    "Update app/permissions.txt, and the terms, DATA-PRIVACY and the data safety of Play when needed",
            )
        }
        checked.get().asFile.writeText(declared.joinToString("\n"))
    }
}

androidComponents {
    onVariants { variant ->
        variant.sources.jniLibs?.addGeneratedSourceDirectory(cargoNdk, CargoTask::outputDir)
        variant.sources.kotlin?.addGeneratedSourceDirectory(uniffiBindgen, CargoTask::outputDir)
        val name = variant.name.replaceFirstChar { it.uppercase() }
        val verify = tasks.register<VerifyPermissions>("verify${name}Permissions") {
            manifest.set(variant.artifacts.get(SingleArtifact.MERGED_MANIFEST))
            allowed.set(layout.projectDirectory.file("permissions.txt"))
            checked.set(layout.buildDirectory.file("permissions/${variant.name}.txt"))
        }
        // before any apk or bundle, installed or published
        tasks.matching { it.name == "package$name" || it.name == "bundle$name" }
            .configureEach { dependsOn(verify) }
    }
}
